# ============================================================
# MR robustness analyses
# ============================================================
#
# Purpose:
#   Perform prespecified robustness analyses for the primary
#   univariable MR analyses using the same harmonized datasets
#   as the primary random-effects IVW analyses.
#
# Methods:
#   1. MR-Egger regression
#   2. Weighted median
#   3. Weighted mode
#   4. MR-RAPS
#
# Important:
#   - No independent SNP selection is performed here.
#   - No LD clumping is performed here.
#   - No independent harmonisation is performed here.
#   - The input datasets must be the same harmonized MR datasets
#     used for the corresponding primary IVW analyses.
#   - Random-effects IVW is the primary analysis and is not
#     repeated in this sensitivity-analysis script.
#   - Fixed-effect IVW is not part of the prespecified workflow.
#
# Input:
#   Harmonized MR datasets generated by 02_Univariable_MR.
#
# Output:
#   results/sensitivity/MR_robustness_results.csv
#
# Software:
#   R >= 4.5.0
#   TwoSampleMR 0.6.29
#   mr.raps 0.4.3
#
# ============================================================


