# ------------------------------------------------------------
# 4. Helper function: validate harmonized MR dataset
# ------------------------------------------------------------

validate_harmonized_data <- function(dat, file_name) {
  
  required_columns <- c(
    "SNP",
    "beta.exposure",
    "se.exposure",
    "beta.outcome",
    "se.outcome",
    "mr_keep"
  )
  
  missing_columns <- setdiff(
    required_columns,
    names(dat)
  )
  
  if (length(missing_columns) > 0) {
    stop(
      paste0(
        "Input file '", file_name,
        "' is missing required columns: ",
        paste(missing_columns, collapse = ", ")
      ),
      call. = FALSE
    )
  }
  
  if (nrow(dat) == 0) {
    stop(
      paste0(
        "Input file '", file_name,
        "' contains no rows."
      ),
      call. = FALSE
    )
  }
  
  dat <- dat %>%
    filter(
      !is.na(SNP),
      !is.na(beta.exposure),
      !is.na(se.exposure),
      !is.na(beta.outcome),
      !is.na(se.outcome)
    )
  
  dat <- dat %>%
    filter(mr_keep == TRUE)
  
  if (nrow(dat) < 2) {
    stop(
      paste0(
        "Input file '", file_name,
        "' contains fewer than 2 valid SNPs after applying mr_keep."
      ),
      call. = FALSE
    )
  }
  
  dat
}


# ------------------------------------------------------------
# 5. Helper function: run MR-RAPS
# ------------------------------------------------------------

run_mr_raps <- function(dat) {
  
  if (nrow(dat) < 3) {
    return(
      tibble(
        method = "MR-RAPS",
        nsnp = nrow(dat),
        b = NA_real_,
        se = NA_real_,
        pval = NA_real_
      )
    )
  }
  
  result <- tryCatch(
    {
      mr.raps::mr.raps(
        beta.exposure = dat$beta.exposure,
        beta.outcome = dat$beta.outcome,
        se.exposure = dat$se.exposure,
        se.outcome = dat$se.outcome
      )
    },
    error = function(e) {
      warning(
        "MR-RAPS failed: ",
        conditionMessage(e),
        call. = FALSE
      )
      
      NULL
    }
  )
  
  if (is.null(result)) {
    return(
      tibble(
        method = "MR-RAPS",
        nsnp = nrow(dat),
        b = NA_real_,
        se = NA_real_,
        pval = NA_real_
      )
    )
  }
  
  tibble(
    method = "MR-RAPS",
    nsnp = nrow(dat),
    b = result$beta.hat,
    se = result$beta.se,
    pval = result$beta.p.value
  )
}


# ------------------------------------------------------------
# 6. Helper function: run robustness analyses
# ------------------------------------------------------------

run_robustness <- function(dat) {
  
  nsnp <- nrow(dat)
  
  results <- list()
  
  # ----------------------------------------------------------
  # MR-Egger
  # ----------------------------------------------------------
  
  if (nsnp >= 3) {
    
    egger_result <- tryCatch(
      {
        TwoSampleMR::mr(
          dat,
          method_list = "mr_egger_regression"
        )
      },
      error = function(e) {
        warning(
          "MR-Egger failed: ",
          conditionMessage(e),
          call. = FALSE
        )
        NULL
      }
    )
    
    if (!is.null(egger_result) && nrow(egger_result) > 0) {
      results[["MR-Egger"]] <- egger_result
    }
    
  } else {
    
    results[["MR-Egger"]] <- tibble(
      method = "MR-Egger",
      nsnp = nsnp,
      b = NA_real_,
      se = NA_real_,
      pval = NA_real_
    )
  }
  
  
  # ----------------------------------------------------------
  # Weighted median
  # ----------------------------------------------------------
  
  if (nsnp >= 3) {
    
    weighted_median_result <- tryCatch(
      {
        TwoSampleMR::mr(
          dat,
          method_list = "mr_weighted_median"
        )
      },
      error = function(e) {
        warning(
          "Weighted median failed: ",
          conditionMessage(e),
          call. = FALSE
        )
        NULL
      }
    )
    
    if (!is.null(weighted_median_result) &&
        nrow(weighted_median_result) > 0) {
      
      results[["Weighted median"]] <- weighted_median_result
    }
    
  } else {
    
    results[["Weighted median"]] <- tibble(
      method = "Weighted median",
      nsnp = nsnp,
      b = NA_real_,
      se = NA_real_,
      pval = NA_real_
    )
  }
  
  
  # ----------------------------------------------------------
  # Weighted mode
  # ----------------------------------------------------------
  
  if (nsnp >= 3) {
    
    weighted_mode_result <- tryCatch(
      {
        TwoSampleMR::mr(
          dat,
          method_list = "mr_weighted_mode"
        )
      },
      error = function(e) {
        warning(
          "Weighted mode failed: ",
          conditionMessage(e),
          call. = FALSE
        )
        NULL
      }
    )
    
    if (!is.null(weighted_mode_result) &&
        nrow(weighted_mode_result) > 0) {
      
      results[["Weighted mode"]] <- weighted_mode_result
    }
    
  } else {
    
    results[["Weighted mode"]] <- tibble(
      method = "Weighted mode",
      nsnp = nsnp,
      b = NA_real_,
      se = NA_real_,
      pval = NA_real_
    )
  }
  
  
  # ----------------------------------------------------------
  # MR-RAPS
  # ----------------------------------------------------------
  
  results[["MR-RAPS"]] <- run_mr_raps(dat)
  
  
  # ----------------------------------------------------------
  # Combine results
  # ----------------------------------------------------------
  
  bind_rows(results)
}


# ------------------------------------------------------------
# 7. Run analyses
# ------------------------------------------------------------

all_results <- vector(
  mode = "list",
  length = length(harmonized_paths)
)

for (i in seq_along(harmonized_paths)) {
  
  input_file <- harmonized_paths[i]
  input_name <- basename(input_file)
  
  message(
    "Processing: ",
    input_name
  )
  
  dat <- readr::read_csv(
    input_file,
    show_col_types = FALSE
  )
  
  dat <- validate_harmonized_data(
    dat = dat,
    file_name = input_name
  )
  
  message(
    "  Valid SNPs: ",
    nrow(dat)
  )
  
  # ----------------------------------------------------------
  # Run robustness analyses on the SAME harmonized dataset
  # used by the primary MR analysis.
  # ----------------------------------------------------------
  
  result <- run_robustness(dat)
  
  # ----------------------------------------------------------
  # Add analysis identifiers
  # ----------------------------------------------------------
  
  exposure_name <- if ("exposure" %in% names(dat)) {
    unique(dat$exposure)[1]
  } else {
    NA_character_
  }
  
  outcome_name <- if ("outcome" %in% names(dat)) {
    unique(dat$outcome)[1]
  } else {
    NA_character_
  }
  
  id_exposure <- if ("id.exposure" %in% names(dat)) {
    unique(dat$id.exposure)[1]
  } else {
    NA_character_
  }
  
  id_outcome <- if ("id.outcome" %in% names(dat)) {
    unique(dat$id.outcome)[1]
  } else {
    NA_character_
  }
  
  result <- result %>%
    mutate(
      id.exposure = id_exposure,
      id.outcome = id_outcome,
      exposure = exposure_name,
      outcome = outcome_name,
      input_file = input_name,
      .before = 1
    )
  
  all_results[[i]] <- result
}


# ------------------------------------------------------------
# 8. Combine all analyses
# ------------------------------------------------------------

robustness_results <- bind_rows(
  all_results
)


# ------------------------------------------------------------
# 9. Reorder columns
# ------------------------------------------------------------

preferred_columns <- c(
